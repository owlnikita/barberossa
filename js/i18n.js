export let currentLanguage = localStorage.getItem("siteLanguage") === "en" ? "en" : "ru";

export function translation(key) {
    return translations[currentLanguage][key] ?? key;
}

export function setLanguage(language) {
    if (!Object.hasOwn(translations, language)) {
        throw new Error(`Unsupported language: ${language}`);
    }

    currentLanguage = language;
    localStorage.setItem("siteLanguage", currentLanguage);
    document.documentElement.lang = currentLanguage;

    document.querySelectorAll("[data-i18n]").forEach((element) => {
        const value = translations[language][element.dataset.i18n];
        if (value !== undefined) {
            element.textContent = value;
        }
    });

    const translatedAttributes = [
        ["aria-label", "i18nAriaLabel"],
        ["placeholder", "i18nPlaceholder"],
        ["alt", "i18nAlt"]
    ];

    for (const [attribute, dataKey] of translatedAttributes) {
        document.querySelectorAll(`[data-i18n-${attribute}]`).forEach((element) => {
            const key = element.dataset[dataKey];
            const value = translations[language][key];
            if (value !== undefined) {
                element.setAttribute(attribute, value);
            }
        });
    }
}
